
-- Dogar Sajji Restaurant
-- Supabase / PostgreSQL database schema

create extension if not exists pgcrypto;

-- Automatically update updated_at fields.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Restaurant menu
create table if not exists public.menu_items (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null default '',
  category text not null default 'General',
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Customer orders
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null default '',
  order_type text not null default 'delivery'
    check (order_type in ('delivery', 'pickup', 'dine_in')),
  payment_method text not null default 'cash'
    check (payment_method in ('cash', 'online', 'card')),
  status text not null default 'new'
    check (status in (
      'new',
      'confirmed',
      'preparing',
      'ready',
      'out_for_delivery',
      'completed',
      'cancelled'
    )),
  subtotal numeric(10,2) not null default 0
    check (subtotal >= 0),
  delivery_fee numeric(10,2) not null default 0
    check (delivery_fee >= 0),
  total numeric(10,2) not null default 0
    check (total >= 0),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Items belonging to each order.
-- Store the name and price at the time of purchase.
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null
    references public.orders(id) on delete cascade,
  menu_item_id uuid
    references public.menu_items(id) on delete set null,
  item_name text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) generated always as
    (unit_price * quantity) stored,
  created_at timestamptz not null default now()
);

-- Keep modification timestamps current.
drop trigger if exists menu_items_updated_at
  on public.menu_items;

create trigger menu_items_updated_at
before update on public.menu_items
for each row execute function public.set_updated_at();

drop trigger if exists orders_updated_at
  on public.orders;

create trigger orders_updated_at
before update on public.orders
for each row execute function public.set_updated_at();

-- Enable Row Level Security on every table.
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Public visitors can view available menu items only.
drop policy if exists "Public can view available menu"
  on public.menu_items;

create policy "Public can view available menu"
on public.menu_items
for select
to anon, authenticated
using (is_available = true);

-- Only a trusted owner role can manage the menu.
-- The owner role must be assigned securely in Supabase
-- app_metadata, never by the user from the website.
drop policy if exists "Owner manages menu"
  on public.menu_items;

create policy "Owner manages menu"
on public.menu_items
for all
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
)
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
);

-- Only the trusted owner can read and manage orders.
drop policy if exists "Owner manages orders"
  on public.orders;

create policy "Owner manages orders"
on public.orders
for all
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
)
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
);

-- Only the trusted owner can read and manage order items.
drop policy if exists "Owner manages order items"
  on public.order_items;

create policy "Owner manages order items"
on public.order_items
for all
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
)
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'owner'
);
